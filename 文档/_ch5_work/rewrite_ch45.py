CJK = re.compile(r"[⺀-鿿　-〿＀-￯]")


def _rpr(attrs):
    e = OxmlElement("w:rPr")
    rf = OxmlElement("w:rFonts")
    for k, v in attrs.items():
        rf.set(qn("w:" + k), v)
    e.append(rf)
    c = OxmlElement("w:color")
    c.set(qn("w:val"), "000000")
    e.append(c)
    return e


def _runs_for(text):
    """按文档约定拆分中英文 run（中文宋体 / 西文 Times New Roman）。"""
    segs = []
    for ch in text:
        lat = not CJK.match(ch)
        if segs and segs[-1][1] == lat:
            segs[-1][0] += ch
        else:
            segs.append([ch, lat])
    out = []
    for s, lat in segs:
        r = OxmlElement("w:r")
        r.append(_rpr({"cs": "Times New Roman"} if lat else
                      {"ascii": "宋体", "hAnsi": "宋体", "cs": "Times New Roman"}))
        t = OxmlElement("w:t")
        t.set(qn("xml:space"), "preserve")
        t.text = s
        r.append(t)
        out.append(r)
    return out


def set_body_text(i, text):
    p_el = P[i]._p
    assert not p_el.findall(".//" + qn("w:drawing")), f"[{i}] 段内含图，不能整段重写"
    for r in p_el.findall(qn("w:r")):
        p_el.remove(r)
    for r in _runs_for(text):
        p_el.append(r)


def set_text_before_drawing(i, text):
    """只替换文字 run，保留段内的图片 run。"""
    p_el = P[i]._p
    runs = p_el.findall(qn("w:r"))
    draw_idx = next(k for k, r in enumerate(runs) if r.findall(".//" + qn("w:drawing")))
    anchor = runs[draw_idx]
    for r in runs[:draw_idx]:
        p_el.remove(r)
    for r in _runs_for(text):
        anchor.addprevious(r)


def set_heading_text(i, text):
    p_el = P[i]._p
    for r in p_el.findall(qn("w:r")):
        p_el.remove(r)
    for r in _runs_for(text):
        p_el.append(r)


def replace_in(i, old, new):
    """改文字引用；跨 run 时整段重写（段内含图则不允许）。"""
    for r in P[i].runs:
        if old in r.text:
            r.text = r.text.replace(old, new, 1)
            return
    full = "".join(r.text for r in P[i].runs)
    if old in full:
        set_body_text(i, full.replace(old, new, 1))
        return
    raise SystemExit(f"[{i}] 未找到 {old!r}")


